class TestDetailedBalance:
    """Verify that symmetrized counts produce detailed-balance-consistent Q."""

    def test_jc_detailed_balance(self):
        alignment, tree, _ = _load_alignment_with_tree(
            os.path.join(DATA_DIR, 'tiny_test.sto'),
            alphabet=['A', 'C', 'G', 'U'],
        )
        A = 4
        Q = np.ones((A, A)) * 1.0
        np.fill_diagonal(Q, -3.0)
        pi = np.ones(A) / A

        result = _compute_subby_counts(alignment, tree, Q, pi, reversible=True)
        new_Q = _m_step_rates(result['waits'], result['mutations'], A)
        new_pi = _stationary_dist(new_Q)

        for i in range(A):
            for j in range(i + 1, A):
                lhs = new_pi[i] * new_Q[i, j]
                rhs = new_pi[j] * new_Q[j, i]
                np.testing.assert_allclose(
                    lhs, rhs, rtol=1e-4,
                    err_msg=f"Detailed balance: {i}<->{j}")

