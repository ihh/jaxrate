def _load_alignment_with_tree(sto_path, alphabet):
    """Load a Stockholm alignment that has an embedded tree."""
    with open(sto_path) as f:
        text = f.read()
    sto = parse_stockholm(text, alphabet=alphabet)
    if hasattr(sto, 'alignment'):
        alignment = sto.alignment
        tree = Tree(
            parentIndex=jnp.array(sto.tree.parentIndex, dtype=jnp.int32),
            distanceToParent=jnp.array(sto.tree.distanceToParent, dtype=jnp.float64),
        )
        return alignment, tree, sto.leaf_names
    raise ValueError("Stockholm file has no embedded tree")


def _load_alignment_with_newick(sto_path, newick, alphabet):
    """Load alignment + tree from separate Stockholm and Newick string."""
    with open(sto_path) as f:
        text = f.read()
    sto = parse_stockholm(text, alphabet=alphabet)
    if isinstance(sto, dict):
        alignment_raw = sto['alignment']
        leaf_names_sto = sto['leaf_names']
    else:
        alignment_raw = sto.alignment
        leaf_names_sto = sto.leaf_names

    tree_result = parse_newick(newick)
    tree = Tree(
        parentIndex=jnp.array(tree_result['parentIndex'], dtype=jnp.int32),
        distanceToParent=jnp.array(tree_result['distanceToParent'], dtype=jnp.float64),
    )

    R = len(tree_result['parentIndex'])
    C = alignment_raw.shape[1]
    gap_token = len(alphabet) + 1
    full_alignment = np.full((R, C), gap_token, dtype=np.int32)

    name_to_row = {name: i for i, name in enumerate(leaf_names_sto)}
    for node_idx in range(R):
        node_name = tree_result['node_names'][node_idx]
        if node_name is not None and node_name in name_to_row:
            full_alignment[node_idx] = alignment_raw[name_to_row[node_name]]

    return full_alignment, tree, leaf_names_sto


def _compute_subby_counts(alignment, tree, Q, pi, reversible=True):
    """Compute expected counts using subby, symmetrizing for reversible models."""
    model = model_from_rate_matrix(
        jnp.array(Q, dtype=jnp.float64),
        jnp.array(pi, dtype=jnp.float64),
        reversible=reversible,
    )
    alignment_jnp = jnp.array(alignment, dtype=jnp.int32)

    counts = Counts(alignment_jnp, tree, model)
    total = np.array(jnp.sum(counts, axis=-1))

    A = Q.shape[0]
    if reversible:
        for i in range(A):
            for j in range(i + 1, A):
                avg = (total[i, j] + total[j, i]) / 2
                total[i, j] = avg
                total[j, i] = avg

    root_post = RootProb(alignment_jnp, tree, model)
    init = np.array(jnp.sum(root_post, axis=-1))

    return {
        'waits': np.diag(total),
        'mutations': total,
        'inits': init,
    }


def _m_step_rates(waits, mutations, A, pseudocounts=0.0):
    """Apply the M-step to get updated Q from expected counts."""
    w = waits.copy() + pseudocounts
    u = mutations.copy()
    np.fill_diagonal(u, 0)
    new_Q = u / np.maximum(w[:, None], 1e-30)
    np.fill_diagonal(new_Q, 0)
    np.fill_diagonal(new_Q, -new_Q.sum(axis=1))
    return new_Q


