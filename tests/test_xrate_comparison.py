# Reference: xrate -g tiny_jc.eg -t out.eg --maxrounds 1 -pi 0 -pm 0 -pt 0
# ---------------------------------------------------------------------------

class TestXrateJC:
    """Compare with xrate on a Jukes-Cantor model (simplest possible case)."""

    # xrate reference values
    XRATE_WAITS = [0.669984, 0.654324, 0.653994, 0.523897]
    XRATE_MUTS_SYM = {
        (0, 1): 0.499498, (0, 2): 0.499521, (0, 3): 0.220944,
        (1, 2): 0.392343, (1, 3): 0.213111, (2, 3): 0.213074,
    }
    XRATE_INITS = [1.36008, 1.18476, 1.39118, 1.06686]
    XRATE_UPDATED_RATES = {
        (0, 1): 0.745536, (0, 2): 0.745571, (0, 3): 0.329775,
        (1, 0): 0.76338, (1, 2): 0.599615, (1, 3): 0.325697,
        (2, 0): 0.7638, (2, 1): 0.599918, (2, 3): 0.325804,
        (3, 0): 0.421733, (3, 1): 0.406781, (3, 2): 0.406709,
    }
    XRATE_RULES = {'S*->': 0.200129, 'S*->S': 0.800515}

    @pytest.fixture
    def setup(self):
        alignment, tree, _ = _load_alignment_with_tree(
            os.path.join(DATA_DIR, 'tiny_test.sto'),
            alphabet=['A', 'C', 'G', 'U'],
        )
        A = 4
        Q = np.ones((A, A)) * 1.0
        np.fill_diagonal(Q, -3.0)
        pi = np.ones(A) / A
        return alignment, tree, Q, pi

    def test_wait_times(self, setup):
        alignment, tree, Q, pi = setup
        result = _compute_subby_counts(alignment, tree, Q, pi)
        np.testing.assert_allclose(result['waits'], self.XRATE_WAITS, rtol=RTOL)

    def test_mutation_counts(self, setup):
        alignment, tree, Q, pi = setup
        result = _compute_subby_counts(alignment, tree, Q, pi)
        for (i, j), xr_val in self.XRATE_MUTS_SYM.items():
            np.testing.assert_allclose(
                result['mutations'][i, j], xr_val, rtol=RTOL,
                err_msg=f"mut[{i},{j}]")

    def test_init_counts(self, setup):
        alignment, tree, Q, pi = setup
        result = _compute_subby_counts(alignment, tree, Q, pi)
        np.testing.assert_allclose(result['inits'], self.XRATE_INITS, rtol=RTOL)

    def test_m_step_rates(self, setup):
        alignment, tree, Q, pi = setup
        result = _compute_subby_counts(alignment, tree, Q, pi)
        new_Q = _m_step_rates(result['waits'], result['mutations'], 4)
        for (i, j), xr_val in self.XRATE_UPDATED_RATES.items():
            np.testing.assert_allclose(
                new_Q[i, j], xr_val, rtol=RTOL,
                err_msg=f"rate[{i},{j}]")

    def test_m_step_row_sums_zero(self, setup):
        alignment, tree, Q, pi = setup
        result = _compute_subby_counts(alignment, tree, Q, pi)
        new_Q = _m_step_rates(result['waits'], result['mutations'], 4)
        np.testing.assert_allclose(new_Q.sum(axis=1), 0, atol=1e-10)

    def test_integrated_em_rates(self, setup):
        """PhyloModel EM step produces rates matching xrate."""
        alignment, tree, Q, pi = setup
        xg = parse_xrate_file(os.path.join(DATA_DIR, 'tiny_jc.eg'))
        pm = PhyloModel(
            grammar=xg.grammar, alignment=alignment, tree=tree,
            chains=[{'rate_matrix': Q.copy(), 'pi': pi.copy(),
                     'update_policy': 'rev'}],
        )
        phylo_em_step(pm, fit_rules=False, fit_rates=True, fit_pi=True,
                      pseudocounts=0.0)
        new_Q = pm.chains[0]['rate_matrix']
        for (i, j), xr_val in self.XRATE_UPDATED_RATES.items():
            np.testing.assert_allclose(
                new_Q[i, j], xr_val, rtol=RTOL,
                err_msg=f"em rate[{i},{j}]")

    def test_integrated_em_rules(self, setup):
        """PhyloModel EM step produces rule probs matching xrate."""
        alignment, tree, Q, pi = setup
        xg = parse_xrate_file(os.path.join(DATA_DIR, 'tiny_jc.eg'))
        pm = PhyloModel(
            grammar=xg.grammar, alignment=alignment, tree=tree,
            chains=[{'rate_matrix': Q.copy(), 'pi': pi.copy(),
                     'update_policy': 'rev'}],
        )
        phylo_em_step(pm, fit_rules=True, fit_rates=False, fit_pi=False,
                      pseudocounts=0.0)
        for rule in pm.grammar.rules:
            nt_name = pm.grammar.nonterminals[rule.lhs].name
            rhs_names = ' '.join(pm.grammar.nonterminals[r].name
                                 for r in rule.rhs)
            key = f"{nt_name}->{rhs_names}"
            if key in self.XRATE_RULES:
                np.testing.assert_allclose(
                    math.exp(rule.log_weight), self.XRATE_RULES[key],
                    rtol=RTOL, err_msg=f"rule {key}")


