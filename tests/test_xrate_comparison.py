"""Tests comparing jaxrate's phylogenetic EM against xrate's expected counts and updated parameters.

Reference data was generated by running xrate (from github.com/ihh/dart) on each
grammar + alignment combination with 1 EM round and zero pseudocounts:

    xrate -g <grammar.eg> -t <out.eg> --maxrounds 1 -pi 0 -pm 0 -pt 0 -q <alignment.sto>

For each test case we verify:
    1. Expected substitution counts (wait times, mutation counts) match
    2. Updated rate matrix Q matches after one M-step
    3. Updated equilibrium distribution pi matches
    4. Updated rule probabilities match

Tolerance: rtol=5e-3 (0.5%) accounts for minor numerical differences between
xrate's Newmat eigendecomposition and JAX/subby's implementation.
"""

